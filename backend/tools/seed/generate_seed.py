#!/usr/bin/env python3
"""Generate FoodWise Flyway seed migrations (V2-V5) from the curated Python data.

Usage:  python3 backend/tools/seed/generate_seed.py
Writes into backend/src/main/resources/db/migration/.

IMPORTANT: Flyway migrations are immutable once applied to any environment.
Regenerate only before first release; afterwards add new V<n>__*.sql files
(this script can be adapted to emit an incremental migration).
UUIDs are deterministic (uuid5) so later migrations can reference seeded rows.
"""
import json
import os
import re
import sys
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from catalog import CATEGORIES, ITEMS  # noqa: E402
from recipes import RECIPES  # noqa: E402
from leftover_rules import LEFTOVER_TYPES, RULES  # noqa: E402

NS = uuid.UUID("6f1d3a52-6c1e-4f5e-9a39-2a4a3c1f0b77")
OUT = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", "src", "main", "resources", "db", "migration"))

CATALOG_UNITS = {"g", "kg", "ml", "L", "pcs", "pkt", "bunch"}
RECIPE_UNITS = CATALOG_UNITS | {"tbsp", "tsp", "pinch"}
LOCATIONS = {"fridge", "freezer", "pantry"}
DIETS = {"vegetarian", "vegan", "eggetarian", "non-vegetarian"}


def uid(kind, key):
    return str(uuid.uuid5(NS, f"{kind}:{key.lower()}"))


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


HEADER = "-- GENERATED by backend/tools/seed/generate_seed.py - do not edit by hand.\n"


def gen_categories():
    lines = [HEADER, "INSERT INTO food_categories (id, slug, name, description, icon_name, color_hex, display_order) VALUES"]
    rows = [f"  ({q(uid('category', s))}, {q(s)}, {q(n)}, {q(d)}, {q(i)}, {q(c)}, {o})" for s, n, d, i, c, o in CATEGORIES]
    return "\n".join(lines) + "\n" + ",\n".join(rows) + ";\n"


def gen_catalog():
    cat_slugs = {c[0] for c in CATEGORIES}
    seen = set()
    rows = []
    for name, hi, cat, unit, loc, perishable, tip in ITEMS:
        assert cat in cat_slugs, (name, cat)
        assert unit in CATALOG_UNITS, (name, unit)
        assert loc in LOCATIONS, (name, loc)
        assert name.lower() not in seen, f"duplicate catalog item {name}"
        seen.add(name.lower())
        rows.append(
            f"  ({q(uid('catalog', name))}, {q(uid('category', cat))}, {q(name)}, {q(hi)}, {q(unit)}, {q(loc)}, "
            f"NULL, NULL, NULL, {q(perishable)}, {q(tip)})"
        )
    head = HEADER + (
        "-- Shelf-life columns are seeded as NULL by policy (PRD FR-EXP-001): no value is approved yet.\n"
        "-- Users must enter expiry dates until validated, Technical-Lead-approved guidance is added in a later migration.\n"
        "INSERT INTO food_catalog (id, category_id, name_en, name_hi, default_unit, default_location,\n"
        "    shelf_life_room_temp_days, shelf_life_fridge_days, shelf_life_freezer_days, is_perishable, common_storage_tip) VALUES\n"
    )
    return head + ",\n".join(rows) + ";\n", seen


def gen_recipes(catalog_names):
    out = [HEADER]
    slugs = set()
    for (title, cuisine, diet, prep, cook, servings, diff, desc, ingredients, steps) in RECIPES:
        assert diet in DIETS, (title, diet)
        assert diff in {"easy", "medium", "hard"}
        slug = slugify(title)
        assert slug not in slugs, f"duplicate recipe {slug}"
        slugs.add(slug)
        rid = uid("recipe", slug)
        out.append(
            "INSERT INTO recipes (id, title, slug, description, cuisine, dietary_type, prep_time_minutes, cook_time_minutes, "
            "servings, difficulty, instructions, is_system_recipe) VALUES\n"
            f"  ({q(rid)}, {q(title)}, {q(slug)}, {q(desc)}, {q(cuisine)}, {q(diet)}, {prep}, {cook}, {servings}, {q(diff)}, "
            f"{q(json.dumps(steps, ensure_ascii=False))}::jsonb, true);"
        )
        rows = []
        names_in_recipe = set()
        for order, ing in enumerate(ingredients):
            name, qty, unit, flags = ing
            assert unit in RECIPE_UNITS, (title, name, unit)
            assert qty > 0, (title, name)
            assert name.lower() not in names_in_recipe, f"{title}: duplicate ingredient {name}"
            names_in_recipe.add(name.lower())
            in_catalog = name.lower() in catalog_names
            if "x" not in flags:
                assert in_catalog, f"{title}: '{name}' is not in the catalog"
            cat_id = uid("catalog", name) if in_catalog else None
            rows.append(
                f"  ({q(uid('ingredient', slug + ':' + name))}, {q(rid)}, {q(cat_id)}, {q(name)}, {qty}, {q(unit)}, "
                f"{q('o' in flags)}, {q('s' in flags)}, {order})"
            )
        required = [i for i in ingredients if "o" not in i[3] and "s" not in i[3]]
        assert required, f"{title}: needs at least one tracked required ingredient"
        out.append(
            "INSERT INTO recipe_ingredients (id, recipe_id, catalog_item_id, ingredient_name, quantity, unit, is_optional, "
            "is_pantry_staple, display_order) VALUES\n" + ",\n".join(rows) + ";\n"
        )
    return "\n".join(out), slugs


def gen_leftovers(recipe_slugs):
    types_sql = ", ".join(q(t) for t in LEFTOVER_TYPES)
    out = [HEADER, f"""-- Leftover repurposing engine (PRD FR-LFT-003, Roadmap Task 6.B1).
-- leftover_type on inventory_batches lets rules match a leftover reliably instead of guessing from free text.
ALTER TABLE inventory_batches ADD COLUMN leftover_type VARCHAR(20)
    CHECK (leftover_type IS NULL OR leftover_type IN ({types_sql}));

CREATE TABLE leftover_repurposing_rules (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    leftover_type  VARCHAR(20) NOT NULL CHECK (leftover_type IN ({types_sql})),
    title          VARCHAR(150) NOT NULL,
    description    TEXT NOT NULL,
    instructions   JSONB NOT NULL DEFAULT '[]'::jsonb,
    recipe_id      UUID REFERENCES recipes (id) ON DELETE SET NULL,
    display_order  INTEGER NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_leftover_rules_type ON leftover_repurposing_rules (leftover_type, display_order);
"""]
    rows = []
    for order, (ltype, title, desc, steps, recipe_title) in enumerate(RULES):
        assert ltype in LEFTOVER_TYPES
        rid = None
        if recipe_title:
            slug = slugify(recipe_title)
            assert slug in recipe_slugs, f"rule {title}: unknown recipe {recipe_title}"
            rid = uid("recipe", slug)
        rows.append(
            f"  ({q(uid('leftover-rule', ltype + ':' + title))}, {q(ltype)}, {q(title)}, {q(desc)}, "
            f"{q(json.dumps(steps, ensure_ascii=False))}::jsonb, {q(rid)}, {order})"
        )
    out.append("INSERT INTO leftover_repurposing_rules (id, leftover_type, title, description, instructions, recipe_id, display_order) VALUES\n"
               + ",\n".join(rows) + ";\n")
    return "\n".join(out)


def write(name, content):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"wrote {path}")


def main():
    write("V2__seed_food_categories.sql", gen_categories())
    catalog_sql, catalog_names = gen_catalog()
    write("V3__seed_food_catalog.sql", catalog_sql)
    recipes_sql, slugs = gen_recipes(catalog_names)
    write("V4__seed_recipes.sql", recipes_sql)
    write("V5__seed_leftover_repurposing_rules.sql", gen_leftovers(slugs))
    print(f"categories={len(CATEGORIES)} catalog={len(ITEMS)} recipes={len(RECIPES)} leftover_rules={len(RULES)}")


if __name__ == "__main__":
    main()
